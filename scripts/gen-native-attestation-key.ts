// scripts/gen-native-attestation-key.ts — สร้าง Ed25519 keypair ของ native attestation signer
//
// การใช้งาน:
//   node scripts/gen-native-attestation-key.ts                # สร้างใหม่/ทับ header + trusted public key
//   node scripts/gen-native-attestation-key.ts --if-missing   # สร้างเฉพาะเมื่อยังไม่มี (ใช้ตอน build:native)
//   node scripts/gen-native-attestation-key.ts --resplit      # แยก seed เดิมเป็น shares (คง keypair เดิม)
//
// กติกา:
// - seed อยู่ใน native/src/generated/native_attestation_key.h ซึ่ง gitignore — ห้าม commit
// - เก็บเป็นสอง share (XOR) ไม่เก็บ seed plaintext ตรง ๆ ในไบนารีที่แจก
// - public key ถูกเขียนลง src/main/attestation/native-trusted-keys.ts ระหว่าง marker
// - ห้าม log seed/private key เด็ดขาด
import { generateKeyPairSync, randomBytes } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const projectRoot = path.resolve(import.meta.dirname, '..')
const generatedDir = path.join(projectRoot, 'native', 'src', 'generated')
const headerPath = path.join(generatedDir, 'native_attestation_key.h')
const trustedKeysSource = path.join(projectRoot, 'src', 'main', 'attestation', 'native-trusted-keys.ts')
const BEGIN_MARKER = '// <ZT-EXAM-NATIVE-ATTESTATION-KEY-BEGIN/>'
const END_MARKER = '// <ZT-EXAM-NATIVE-ATTESTATION-KEY-END/>'

const onlyIfMissing = process.argv.includes('--if-missing')
const resplitOnly = process.argv.includes('--resplit')

function parseByteArray(block: string): Buffer | null {
  const bytes = [...block.matchAll(/0x([0-9a-fA-F]{2})/g)].map((match) =>
    Number.parseInt(match[1] ?? '', 16)
  )
  return bytes.length === 32 ? Buffer.from(bytes) : null
}

function readHeaderBlock(pattern: RegExp): Buffer | null {
  if (!fs.existsSync(headerPath)) return null
  const source = fs.readFileSync(headerPath, 'utf8')
  const match = pattern.exec(source)
  if (!match?.[1]) return null
  return parseByteArray(match[1])
}

function trustedPublicHex(): string | null {
  if (!fs.existsSync(trustedKeysSource)) return null
  const source = fs.readFileSync(trustedKeysSource, 'utf8')
  const match = /NATIVE_ATTESTATION_PUBLIC_KEY_HEX\s*=\s*'([0-9a-f]{64})'/.exec(source)
  return match?.[1] ?? null
}

function headerPublicHex(): string | null {
  return readHeaderBlock(/kPublicKey\[32\]\s*=\s*\{([\s\S]*?)\};/)?.toString('hex') ?? null
}

/** อ่าน seed เดิมได้ทั้งแบบ plaintext (legacy) และแบบสอง share */
function headerSeed(): Buffer | null {
  const legacy = readHeaderBlock(/kSigningSeed\[32\]\s*=\s*\{([\s\S]*?)\};/)
  if (legacy) return legacy
  const shareA = readHeaderBlock(/kSeedShareA\[32\]\s*=\s*\{([\s\S]*?)\};/)
  const shareB = readHeaderBlock(/kSeedShareB\[32\]\s*=\s*\{([\s\S]*?)\};/)
  if (!shareA || !shareB) return null
  return Buffer.from(shareA.map((value, index) => value ^ (shareB[index] ?? 0)))
}

function splitSeed(seed: Buffer): { a: Buffer; b: Buffer } {
  const a = randomBytes(seed.length)
  const b = Buffer.alloc(seed.length)
  for (let i = 0; i < seed.length; i += 1) b[i] = seed[i]! ^ a[i]!
  return { a, b }
}

function formatBytes(bytes: Buffer): string {
  const parts: string[] = []
  for (let i = 0; i < bytes.length; i += 8) {
    const row = [...bytes.subarray(i, i + 8)]
      .map((value) => `0x${value.toString(16).padStart(2, '0')}`)
      .join(', ')
    parts.push(`  ${row}`)
  }
  return parts.join(',\n')
}

function writeHeader(shares: { a: Buffer; b: Buffer }, publicRaw: Buffer): void {
  const header = `#pragma once
// AUTO-GENERATED by scripts/gen-native-attestation-key.ts — DO NOT COMMIT
// ไฟล์นี้มี private seed (แยกเป็นสอง share) ของ native attestation signer (gitignored)
// หมายเหตุ: การแยก share เป็นเพียงการเพิ่มต้นทุน reverse engineering — ไม่ใช่ root of trust
#include <cstdint>

namespace zt_exam_native_attestation {

inline constexpr std::uint8_t kSeedShareA[32] = {
${formatBytes(shares.a)}
};

inline constexpr std::uint8_t kSeedShareB[32] = {
${formatBytes(shares.b)}
};

inline constexpr std::uint8_t kPublicKey[32] = {
${formatBytes(publicRaw)}
};

}  // namespace zt_exam_native_attestation
`
  fs.mkdirSync(generatedDir, { recursive: true })
  fs.writeFileSync(headerPath, header, { mode: 0o600 })
}

if (resplitOnly) {
  const seed = headerSeed()
  const publicRaw = readHeaderBlock(/kPublicKey\[32\]\s*=\s*\{([\s\S]*?)\};/)
  if (!seed || !publicRaw) {
    console.error('ไม่พบ seed/public key เดิมใน header — ใช้โหมดสร้างใหม่แทน')
    process.exit(1)
  }
  writeHeader(splitSeed(seed), publicRaw)
  console.log(`Re-split แล้ว: ${path.relative(projectRoot, headerPath)} (keypair เดิม ไม่แตะ trusted key)`)
  process.exit(0)
}

if (onlyIfMissing) {
  const headerKey = headerPublicHex()
  const trustedKey = trustedPublicHex()
  if (headerKey && trustedKey && headerKey === trustedKey) {
    console.log('native attestation key มีอยู่แล้วและตรงกับ trusted key — ข้ามการสร้าง (--if-missing)')
    process.exit(0)
  }
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519')
const publicJwk = publicKey.export({ format: 'jwk' }) as { x?: string }
const privateJwk = privateKey.export({ format: 'jwk' }) as { d?: string }

if (!publicJwk.x || !privateJwk.d) {
  console.error('สร้าง Ed25519 keypair ไม่สำเร็จ (JWK ไม่มี x/d)')
  process.exit(1)
}

const publicRaw = Buffer.from(publicJwk.x, 'base64url')
const seed = Buffer.from(privateJwk.d, 'base64url')
if (publicRaw.length !== 32 || seed.length !== 32) {
  console.error('ขนาดกุญแจ Ed25519 ไม่ถูกต้อง')
  process.exit(1)
}

writeHeader(splitSeed(seed), publicRaw)

const publicHex = publicRaw.toString('hex')
if (!fs.existsSync(trustedKeysSource)) {
  console.error(`ไม่พบ ${trustedKeysSource}`)
  process.exit(1)
}
const current = fs.readFileSync(trustedKeysSource, 'utf8')
const start = current.indexOf(BEGIN_MARKER)
const end = current.indexOf(END_MARKER)
if (start < 0 || end < 0 || end <= start) {
  console.error(`ไม่พบ marker ใน ${trustedKeysSource} — ไม่ปรับปรุงไฟล์อัตโนมัติ`)
  process.exit(1)
}
const block = `${BEGIN_MARKER}
export const NATIVE_ATTESTATION_PUBLIC_KEY_HEX = '${publicHex}'
${END_MARKER}`
const updated = current.slice(0, start) + block + current.slice(end + END_MARKER.length)
fs.writeFileSync(trustedKeysSource, updated)

console.log(`Native key : ${path.relative(projectRoot, headerPath)} (split seed — gitignored, ห้าม commit)`)
console.log(`Public key : ${publicHex}`)
console.log(`Trusted TS : ${path.relative(projectRoot, trustedKeysSource)}`)
